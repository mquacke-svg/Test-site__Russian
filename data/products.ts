/** Товары одной категории в порядке объявления */
export function getProductsByCategory(categoryId: CategoryId): Product[] {
  return products.filter((product) => product.category === categoryId);
}

/** Хиты продаж для главной страницы */
export function getBestsellers(): Product[] {
  return products.filter((product) => product.isBestseller);
}

/** Товар по slug */
export function getProductById(id: string): Product | undefined {
  return products.find((product) => product.id === id);
}

/** Минимальная цена позиции: обычная цена или самый дешёвый вариант */
export function getMinPrice(product: Product): number | null {
  if (product.price !== null) return product.price;
  if (product.variants && product.variants.length > 0) {
    return Math.min(...product.variants.map((variant) => variant.price));
  }
  return null;
}

/** Цена для витрины: «105 ₽» или «от 175 ₽» для напитков */
export function formatPrice(product: Product): string {
  if (product.price !== null) return `${product.price} ₽`;
  const min = getMinPrice(product);
  if (min === null) return 'по запросу';
  return `от ${min} ₽`;
}
