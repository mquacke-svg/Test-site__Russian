export type CategoryId =
  | 'pastry'
  | 'eclairs'
  | 'cakes'
  | 'sandwiches'
  | 'kitchen'
  | 'desserts'
  | 'coffee'
  | 'tea';

export interface Category {
  /** Slug латиницей — используется в URL и якорях меню */
  id: CategoryId;
  /** Название для витрины */
  name: string;
  /** Эмодзи-иконка для навигации по категориям */
  emoji: string;
  /** Короткий подзаголовок для секции */
  tagline: string;
}

/** Вариант напитка: объём + цена за него */
export interface ProductVariant {
  /** Объём в миллилитрах */
  volumeMl: number;
  /** Подпись для витрины, например «350 мл» */
  label: string;
  /** Цена в рублях */
  price: number;
}

export interface Product {
  /** Slug латиницей, уникален в рамках всего каталога */
  id: string;
  /** Название на русском */
  name: string;
  /** Цена в рублях. null — если цена зависит от объёма (см. variants) */
  price: number | null;
  /** Варианты по объёму — только для напитков. null для штучных позиций */
  variants: ProductVariant[] | null;
  /** Категория каталога */
  category: CategoryId;
  /** Путь к фото в /public. null — фото пока нет */
  image: string | null;
  /** Краткое аппетитное описание. null — если описания нет */
  description: string | null;
  /** Хит продаж — выносим на главную */
  isBestseller: boolean;
  /** Сезонная позиция (например, пасхальный кулич) */
  isSeasonal?: boolean;
}

